def register_default_capabilities(registry: CapabilityRegistry | None = None) -> CapabilityRegistry:
    target = registry or get_capability_registry()
    for entry in DEFAULT_CAPABILITIES:
        existing = target.get_or_none(entry.descriptor.id)
        target.register(entry.descriptor)
        if existing is None:
            target.update_status(
                entry.descriptor.id,
                entry.initial_state,
                entry.initial_reason,
                health_score=1.0 if entry.initial_state == CapabilityState.READY else 0.7,
            )
    return target
