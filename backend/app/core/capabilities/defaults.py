@dataclass(frozen=True)
class DefaultCapability:
    descriptor: CapabilityDescriptor
    initial_state: CapabilityState
    initial_reason: str


def _descriptor(
    *,
    capability_id: str,
    name: str,
    category: Category,
    criticality: Criticality,
    activation_mode: Mode,
    dependencies: list[str] | None = None,
    description: str,
    owner: str,
    resource_profile: list[Resource] | None = None,
    config_key: str | None = None,
    component_path: str | None = None,
    metadata: dict | None = None,
) -> CapabilityDescriptor:
    return CapabilityDescriptor(
        id=capability_id,
        name=name,
        category=category,
        criticality=criticality,
        activation_mode=activation_mode,
        dependencies=dependencies or [],
        description=description,
        owner=owner,
        resource_profile=resource_profile or [Resource.CPU_LIGHT],
        config_key=config_key,
        component_path=component_path,
        metadata=metadata or {},
    )


def _cold_reason() -> str:
    return "Registered as a core capability; awaiting managed activation."


def _startup_ready_reason() -> str:
    return "Registered during backend startup with a lightweight readiness check."


